# Builds, signs and installs the TV launcher, then opens it on the TV.
# Signing uses the "TVLauncher" security profile (your Apps2Samsung certificate).
#   .\launcher-deploy.ps1           build + install + open
#   .\launcher-deploy.ps1 -NoRun    build + install only
param([switch]$NoRun)

$tizen = "$env:USERPROFILE\tizen-studio\tools\ide\bin\tizen.bat"
$sdb = "$env:USERPROFILE\tizen-studio\tools\sdb.exe"
$tv = '192.168.1.46:26101'
$src = Join-Path $PSScriptRoot 'launcher'
# Build in a temp copy so signature files never land in the repo.
$build = Join-Path $env:TEMP 'tvlauncher-build'

if (Test-Path $build) { Remove-Item $build -Recurse -Force }
Copy-Item $src $build -Recurse

& $sdb connect 192.168.1.46 | Out-Null

# Store apps only report "visible" under their Smart Hub number, so map Tizen IDs to those
# from the TV's current app list. Falls back to the committed js/appids.js if this fails.
$list = & $sdb -s $tv shell 0 vd_applist 2>$null | Out-String
$map = [ordered]@{}
foreach ($blk in ($list -split '-{90,}')) {
  $id = [regex]::Match($blk, '-{5,}app_id\s*=(.*?)-{5,}').Groups[1].Value
  $tz = [regex]::Match($blk, '-{5,}app_tizen_id\s*=(.*?)-{5,}').Groups[1].Value
  if ($id -and $tz -and $id -ne $tz) { $map[$tz] = $id }
}
if ($map.Count) {
  $js = "// Generated by launcher-deploy.ps1 from sdb vd_applist`nconst STORE_IDS = $($map | ConvertTo-Json -Compress);"
  Set-Content -Path (Join-Path $build 'js\appids.js') -Value $js -Encoding utf8
  "Store IDs mapped: $($map.Count)"
}

& $tizen package -t wgt -s TVLauncher -- $build
$wgt = Get-ChildItem $build -Filter *.wgt | Select-Object -First 1
if (-not $wgt) { Write-Error 'Packaging failed, no .wgt produced'; exit 1 }

& $tizen install -n $wgt.Name -s $tv -- $build
if ($LASTEXITCODE -ne 0) { Write-Error 'Install failed'; exit 1 }

if (-not $NoRun) { & $sdb -s $tv shell 0 was_execute HDvLaunchr.Home }
